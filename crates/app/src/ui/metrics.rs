//! 界面度量：圆角四档。**改观感先看这里。**
//!
//! 颜色在 `colors.rs`，文案在 `strings.rs`，几何在这儿。三样分开是因为判断标准不同：
//! 颜色看对比度，文案看语气，几何看嵌套关系。
//!
//! 圆角只有四档，按「谁嵌在谁里面」选，不按元素类型随手加新的数：
//!
//! | 档 | 值 | 用在哪 |
//! | --- | --- | --- |
//! | [`RADIUS_CHIP`] | 4 | 键帽、快捷键小块——行内最小的块 |
//! | [`RADIUS_CONTROL`] | 6 | 按钮、分段内块、列表行 |
//! | [`RADIUS_SURFACE`] | 8 | 分段的底座、设置项这类容器 |
//! | [`RADIUS_CARD`] | 10 | 浮在最上面的卡片（新增 / 编辑、提示框） |
//!
//! 相邻两档差 2，是照着分段控件那个间隙定的：底座 8、内块 6、中间 `p_0p5`(2px) 隔开，
//! 正好是「内层 = 外层 − 间隙」。同值嵌套（8 里放 8）看起来像两层一样的纸叠在一起，
//! 转角处会糊成一条粗边。
//!
//! **面板自己那圈圆角不在这里**：它必须等于系统窗口裁剪的圆角（`launcher::CORNER_RADIUS`，
//! 物理像素、不随 DPI 缩放），改它等于在四个角上开口子。

/// 行内最小的块：页脚键帽、列表行里的快捷键小块。
pub(crate) const RADIUS_CHIP: f32 = 4.;

/// 按钮、分段控件里被选中的那一块、列表行的高亮块。
pub(crate) const RADIUS_CONTROL: f32 = 6.;

/// 容器：分段控件的底座、设置项那一类承托面。
pub(crate) const RADIUS_SURFACE: f32 = 8.;

/// 浮在最上面的卡片：新增 / 编辑弹窗、「文件不在了」提示。
pub(crate) const RADIUS_CARD: f32 = 10.;
